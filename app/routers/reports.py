router = APIRouter()

BASE = "/admin/reports"
templates.env.filters["inr"] = inr

NON_MONEY_HEADERS = {"Items", "Settings"}
_DDMMYYYY = None


def _admin(request: Request) -> None:
    if not is_admin(request):
        raise HTTPException(403, detail="Reports are for administrators only.")


def _generated_by(request: Request) -> str:
    return getattr(request.state, "username", None) or audit_svc.current_user_label.get() or "admin"


def _month_options(ctx: svc.Ctx) -> list[tuple[str, str]]:
    seen = set(ctx.periods) | {e["ym"] for e in ctx.entries if e["ym"] is not None}
    today_ym = svc.ym_of(ist_today())
    seen.add(today_ym)
    lo, hi = min(seen), max(seen)
    return [(svc.ym_value(y), svc.ym_label(y)) for y in range(max(lo, hi - 59), hi + 1)]


def _fy_options(ctx: svc.Ctx) -> list[tuple[int, str]]:
    seen = set(ctx.periods) | {e["ym"] for e in ctx.entries if e["ym"] is not None}
    today = ist_today()
    first = svc.current_fy(date(min(seen) // 12, min(seen) % 12 + 1, 1)) if seen else svc.current_fy(today)
    return [(fy, svc.fy_label(fy)) for fy in range(first, svc.current_fy(today) + 1)]


def _context(request: Request, db: Session, p: svc.Params) -> dict:
    data = svc.build(db, p)
    ctx = data["ctx"]
    flats = db.scalars(select(Flat).order_by(Flat.number)).all()
    scope = svc.scope_text(ctx)
    export_q = p.url("", drill=p.drill_query()).lstrip("?")
    return {
        "request": request, "p": p, "d": data, "kinds": svc.KINDS, "cats": svc.CATS, "reasons": svc.REASONS,
        "flats": flats, "month_options": _month_options(ctx), "fy_options": _fy_options(ctx),
        "fy_selected": p.fy if p.fy is not None else svc.current_fy(ist_today()), "scope_text": scope,
        "glossary": svc.GLOSSARY, "export_query": export_q, "ym_value": svc.ym_value,
        "back_url": p.url(BASE), "page_size": svc.PAGE_SIZE,
        "filters": svc.filter_lines(db, p, ctx),
        "from_value": svc.ym_value(p.ym_from) if p.ym_from is not None else "",
        "to_value": svc.ym_value(p.ym_to) if p.ym_to is not None else "",
        "drill_cols": svc.DRILL_COLUMNS, "row_values": svc.drill_row_values,
        "ist_stamp": svc._ist_stamp, "chart": Markup(data.get("chart") or ""),
    }


@router.get(BASE, response_class=HTMLResponse)
def reports_page(request: Request, db: Session = Depends(get_db)):
    _admin(request)
    p = svc.parse(request.query_params)
    p.measure = ""
    return templates.TemplateResponse(request, "admin_reports.html", _context(request, db, p))


@router.get(BASE + "/drill", response_class=HTMLResponse)
def reports_drill(request: Request, db: Session = Depends(get_db)):
    _admin(request)
    p = svc.parse(request.query_params)
    if not p.measure:
        return Response(status_code=303, headers={"Location": p.url(BASE)})
    return templates.TemplateResponse(request, "admin_reports.html", _context(request, db, p))


def _download(content: bytes, name: str, mime: str) -> Response:
    return Response(content, media_type=mime, headers={"Content-Disposition": f'attachment; filename="{name}"'})


def _stamp() -> str:
    return ist_now().strftime("%Y%m%d-%H%M")


def _filters_text(lines: list[tuple[str, str]]) -> str:
    return "; ".join(f"{k}: {v}" for k, v in lines)


def _audit(db: Session, request: Request, fmt: str, title: str, lines, rows: int) -> None:
    audit_svc.log_audit(
        db, entity_type="report", entity_id=None, action="export", user_label=_generated_by(request),
        after={"report": title, "format": fmt, "filters": _filters_text(lines), "rows": rows},
    )
    db.commit()


def _flatten(tables: list[dict]) -> int:
    return sum(len(t["rows"]) for t in tables)


def _param_rows(request: Request, lines) -> list[list]:
    return [list(x) for x in lines] + [["Generated at", format_ist_stamp()], ["App version", APP_VERSION],
                                       ["Generated by", _generated_by(request)]]


@router.get(BASE + "/export.csv")
def reports_csv(request: Request, db: Session = Depends(get_db)):
    _admin(request)
    p = svc.parse(request.query_params)
    pkg = svc.export_package(db, p)
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow([f"{PORTAL_NAME} - {pkg['title']}"])
    for row in _param_rows(request, pkg["params"]):
        w.writerow(row)
    for t in pkg["tables"]:
        w.writerow([])
        w.writerow([t["title"]])
        w.writerow(t["header"])
        w.writerows(t["rows"])
        if t["total"]:
            w.writerow(t["total"])
    _audit(db, request, "csv", pkg["title"], pkg["params"], _flatten(pkg["tables"]))
    return _download(("\ufeff" + buf.getvalue()).encode("utf-8"), f"report-{_stamp()}.csv", "text/csv")


def _xl_value(header: str, v):
    if isinstance(v, str):
        if header == "Date" and len(v) == 10 and v[2] == "-" and v[5] == "-":
            try:
                return datetime.strptime(v, "%d-%m-%Y").date()
            except ValueError:
                return v
        if header.startswith("Recorded at") and v.endswith(" IST"):
            try:
                return datetime.strptime(v[:-4], "%d-%m-%Y %H:%M")
            except ValueError:
                return v
    return v


def _write_table(ws, table: dict, bold, start_row: int | None = None) -> None:
    ws.append([table["title"]])
    ws.cell(row=ws.max_row, column=1).font = bold
    ws.append(table["header"])
    for c in ws[ws.max_row]:
        c.font = bold
    money_cols = {i for i, h in enumerate(table["header"]) if h not in NON_MONEY_HEADERS}
    for row in table["rows"] + ([table["total"]] if table["total"] else []):
        ws.append([_xl_value(table["header"][i] if i < len(table["header"]) else "", v) for i, v in enumerate(row)])
        for i, c in enumerate(ws[ws.max_row]):
            if isinstance(c.value, datetime):
                c.number_format = 'dd-mm-yyyy hh:mm "IST"'
            elif isinstance(c.value, date):
                c.number_format = "dd-mm-yyyy"
            elif isinstance(c.value, int) and i in money_cols:
                c.number_format = "#,##0"
    if table["total"]:
        for c in ws[ws.max_row]:
            c.font = bold
    ws.append([])


@router.get(BASE + "/export.xlsx")
def reports_xlsx(request: Request, db: Session = Depends(get_db)):
    from openpyxl import Workbook
    from openpyxl.styles import Font

    _admin(request)
    p = svc.parse(request.query_params)
    pkg = svc.workbook_package(db, p)
    bold = Font(bold=True)
    wb = Workbook()
    ws = wb.active
    ws.title = "Parameters"
    ws.append([f"{PORTAL_NAME} - report parameters"])
    ws.cell(row=1, column=1).font = bold
    for row in _param_rows(request, pkg["params"]):
        ws.append(row)
    ws.column_dimensions["A"].width = 34
    ws.column_dimensions["B"].width = 60
    sheet = wb.create_sheet("Summary")
    for t in pkg["summary"]:
        _write_table(sheet, t, bold)
    _write_table(wb.create_sheet("Trend"), pkg["trend"], bold)
    _write_table(wb.create_sheet("Details"), pkg["details"], bold)
    for s in wb.worksheets[1:]:
        s.column_dimensions["A"].width = 26
    out = io.BytesIO()
    wb.save(out)
    title = pkg["details"]["title"] if p.is_drill else svc.KINDS[p.kind]
    _audit(db, request, "xlsx", title, pkg["params"], len(pkg["details"]["rows"]) + _flatten(pkg["summary"]))
    return _download(out.getvalue(), f"report-{_stamp()}.xlsx",
                     "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet")


@router.get(BASE + "/export.pdf")
def reports_pdf(request: Request, db: Session = Depends(get_db)):
    from reportlab.lib.pagesizes import A4, landscape
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer

    from app.services.pdf_report import _table, rs

    _admin(request)
    p = svc.parse(request.query_params)
    pkg = svc.export_package(db, p)
    styles = getSampleStyleSheet()
    cell = styles["BodyText"].clone("rcell", fontSize=7, leading=8.5)
    story = [Paragraph(escape(f"{PORTAL_NAME} - {pkg['title']}"), styles["Title"])]
    for k, v in _param_rows(request, pkg["params"]):
        story.append(Paragraph(f"<b>{escape(k)}:</b> {escape(str(v))}", styles["BodyText"]))

    def fmt(header: str, v):
        if isinstance(v, int) and header not in NON_MONEY_HEADERS:
            return rs(v)
        return Paragraph(escape(str(v)), cell)

    for t in pkg["tables"]:
        story += [Spacer(1, 4 * mm), Paragraph(escape(t["title"]), styles["Heading3"])]
        rows = [[Paragraph(f"<b>{escape(str(h))}</b>", cell) for h in t["header"]]]
        for r in t["rows"] + ([t["total"]] if t["total"] else []):
            rows.append([fmt(t["header"][i] if i < len(t["header"]) else "", v) for i, v in enumerate(r)])
        story.append(_table(rows, None, total_row=bool(t["total"])))
    title = pkg["title"]

    def numbered(canvas, doc):
        canvas.saveState()
        canvas.setFont("Helvetica", 7.5)
        canvas.drawString(10 * mm, 6 * mm, f"{PORTAL_NAME} - {title} - generated {format_ist_stamp()}")
        canvas.drawRightString(landscape(A4)[0] - 10 * mm, 6 * mm, f"Page {doc.page}")
        canvas.restoreState()

    out = io.BytesIO()
    SimpleDocTemplate(out, pagesize=landscape(A4), leftMargin=10 * mm, rightMargin=10 * mm, topMargin=10 * mm,
                      bottomMargin=12 * mm, title=f"{PORTAL_NAME} - {title}").build(story, onFirstPage=numbered, onLaterPages=numbered)
    _audit(db, request, "pdf", title, pkg["params"], _flatten(pkg["tables"]))
    return _download(out.getvalue(), f"report-{_stamp()}.pdf", "application/pdf")
